export function isRtl(locale: Locale): boolean {
	return locale === "ar";
}

const STORAGE_KEY = "locale";

function isLocale(value: string | null): value is Locale {
	return value === "ar" || value === "en" || value === "de";
}

function readStoredLocale(): Locale | null {
	if (typeof window === "undefined") return null;
	try {
		const stored = window.localStorage.getItem(STORAGE_KEY);
		return isLocale(stored) ? stored : null;
	} catch {
		// localStorage can throw in sandboxed/partitioned contexts (e.g. the
		// VSCode integrated browser) or when storage is disabled.
		return null;
	}
}

function storeLocale(locale: Locale) {
	if (typeof window === "undefined") return;
	try {
		window.localStorage.setItem(STORAGE_KEY, locale);
	} catch {
		// Ignore — see readStoredLocale.
	}
}

function applyDocumentLocale(locale: Locale) {
	if (typeof document === "undefined") return;
	document.documentElement.lang = locale;
	document.documentElement.dir = isRtl(locale) ? "rtl" : "ltr";
}

type I18nCtx = {
	locale: Locale;
	rtl: boolean;
	setLocale: (l: Locale) => void;
	t: (key: string, vars?: Record<string, string | number>) => string;
};

const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({
	initialLocale = "ar",
	children,
}: {
	initialLocale?: Locale;
	children: ReactNode;
}) {
	const [locale, setLocaleState] = useState<Locale>(initialLocale);

	// Read the persisted locale after mount so the server-rendered markup (which
	// always uses initialLocale) matches the first client render — avoids a
	// hydration mismatch — then reconcile on the client.
	useEffect(() => {
		const stored = readStoredLocale();
		if (stored && stored !== locale) setLocaleState(stored);
		applyDocumentLocale(stored ?? locale);
		// Run once on mount.
		// eslint-disable-next-line react-hooks/exhaustive-deps
	}, []);

	const setLocale = (l: Locale) => {
		setLocaleState(l);
		storeLocale(l);
		applyDocumentLocale(l);
	};

	const t = (key: string, vars?: Record<string, string | number>) => {
		let s = messages[locale][key] ?? messages.en[key] ?? key;
		if (vars)
			for (const [k, v] of Object.entries(vars))
				s = s.replace(`{${k}}`, String(v));
		return s;
	};
	return (
		<Ctx.Provider value={{ locale, rtl: isRtl(locale), setLocale, t }}>
			{children}
		</Ctx.Provider>
	);
}

export function useI18n(): I18nCtx {
	const ctx = useContext(Ctx);
	if (!ctx) throw new Error("useI18n must be used within I18nProvider");
	return ctx;
}
